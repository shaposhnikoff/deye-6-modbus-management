"""Generate ``deye_monitoring/registers.py`` from the vendored ESPHome register map.

The upstream package (scrhall/deye-sun6k-waveshare-esphome, Apache-2.0) keeps the
register definitions in ESPHome YAML. This script extracts the read-only numeric
sensors and emits a frozen tuple of :class:`Register` entries.

Run with:  uv run python tools/generate_registers.py
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAP_DIR = ROOT / "tools" / "upstream-map"
TARGET = ROOT / "src" / "deye_monitoring" / "registers.py"

ENTRY_SPLIT = re.compile(r"^\s*-\s+platform:\s*modbus_controller\s*$", re.MULTILINE)

# Upstream exposes these as text sensors (string lambdas), so they are skipped by
# the YAML parser above. The raw words carry useful data, so they are added here.
EXTRA_REGISTERS: tuple[dict[str, object], ...] = (
    {
        "name": "Running Status",
        "address": 0x003B,
        "value_type": "U_WORD",
        "scale": 1.0,
        "offset": 0.0,
        "unit": "",
        "group": "device",
        "shift": 0,
        "mask": 0xFFFF,
    },
)

HEADER = '''"""Register map for the Deye hybrid inverter (holding registers, read-only).

Generated by ``tools/generate_registers.py`` from the ESPHome package
``scrhall/deye-sun6k-waveshare-esphome`` (Apache-2.0). Do not edit by hand.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Register:
    """One holding register with its decoding rules."""

    name: str
    address: int
    value_type: str
    scale: float
    offset: float
    unit: str
    group: str
    shift: int = 0
    mask: int = 0xFFFF


REGISTERS: tuple[Register, ...] = (
'''

FOOTER = ")\n"


def parse_entries() -> list[dict[str, object]]:
    entries: list[dict[str, object]] = []
    seen: set[tuple[str, int]] = set()
    for path in sorted(MAP_DIR.glob("*.yaml")):
        text = path.read_text(encoding="utf-8")
        for part in ENTRY_SPLIT.split(text)[1:]:
            block = part.split("\n  - platform:")[0]

            def grab(key: str, block: str = block) -> str | None:
                match = re.search(rf"^\s+{key}:\s*(.+?)\s*$", block, re.MULTILINE)
                if not match:
                    return None
                return match.group(1).strip().strip("\"'")

            name, address, value_type = grab("name"), grab("address"), grab("value_type")
            if not name or address is None:
                continue
            # Text sensors (serial number, running status) carry lambdas that
            # return strings; they are handled separately or skipped.
            if "raw_encode" in block or "std::string" in block:
                continue
            if value_type is None:
                if grab("register_type") != "holding":
                    continue
                value_type = "U_WORD"
            if value_type not in {"U_WORD", "S_WORD", "U_DWORD", "U_DWORD_R"}:
                continue
            if "#" in name:
                continue

            shift, mask = 0, 0xFFFF
            bit_field = re.search(r"value\s*>>\s*(\d+)\)\s*&\s*(0x[0-9A-Fa-f]+|\d+)", block)
            if bit_field:
                shift, mask = int(bit_field.group(1)), int(bit_field.group(2), 0)
            else:
                plain_mask = re.search(r"value\s*&\s*(0x[0-9A-Fa-f]+|\d+)", block)
                if plain_mask:
                    mask = int(plain_mask.group(1), 0)

            scale = 1.0
            for operation, factor in (("multiply", "mul"), ("divide", "div")):
                match = re.search(rf"^\s+-\s+{operation}:\s*(-?[\d.]+)\s*$", block, re.MULTILINE)
                if match:
                    value = float(match.group(1))
                    scale = scale * value if factor == "mul" else scale / value
            offset = 0.0
            for operation in ("offset", "add"):
                match = re.search(rf"^\s+-\s+{operation}:\s*(-?[\d.]+)\s*$", block, re.MULTILINE)
                if match:
                    offset += float(match.group(1))

            key = (name, int(address, 0))
            if key in seen:
                continue
            seen.add(key)
            entries.append(
                {
                    "name": name,
                    "address": int(address, 0),
                    "value_type": value_type,
                    "scale": scale,
                    "offset": offset,
                    "unit": grab("unit_of_measurement") or "",
                    "group": path.stem,
                    "shift": shift,
                    "mask": mask,
                }
            )
    for extra in EXTRA_REGISTERS:
        key = (str(extra["name"]), int(extra["address"]))
        if key not in seen:
            seen.add(key)
            entries.append(dict(extra))
    entries.sort(key=lambda entry: (str(entry["group"]), int(entry["address"])))
    return entries


def render(entries: list[dict[str, object]]) -> str:
    lines = [HEADER]
    for entry in entries:
        parts = [
            f"name={entry['name']!r}",
            f"address=0x{int(entry['address']):04X}",
            f"value_type={entry['value_type']!r}",
            f"scale={entry['scale']!r}",
            f"offset={entry['offset']!r}",
            f"unit={entry['unit']!r}",
            f"group={entry['group']!r}",
        ]
        if entry["shift"]:
            parts.append(f"shift={entry['shift']!r}")
        if entry["mask"] != 0xFFFF:
            parts.append(f"mask=0x{int(entry['mask']):04X}")
        lines.append("    Register(" + ", ".join(parts) + "),\n")
    lines.append(FOOTER)
    return "".join(lines)


def main() -> None:
    """Write the generated module."""
    entries = parse_entries()
    TARGET.write_text(render(entries), encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} with {len(entries)} registers")


if __name__ == "__main__":
    main()
